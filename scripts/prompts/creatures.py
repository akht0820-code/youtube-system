# ── 構成生成プロンプト ────────────────────────────────────

def build_structure_prompt(theme: str,
                           opening_pattern: str = "A",
                           ending_pattern: str = "1") -> str:
    """テーマ+冒頭/結末パターンから5幕構成を生成するプロンプト。

    Args:
        theme: 生き物のテーマ名（例: 「カモノハシ」「ミツバチ」）
        opening_pattern: 冒頭パターンID ("A"〜"F")
        ending_pattern: 結末パターンID ("1"〜"5")
    """
    op = OPENING_PATTERNS.get(opening_pattern, OPENING_PATTERNS["A"])
    ed = ENDING_PATTERNS.get(ending_pattern, ENDING_PATTERNS["1"])

    op_hint = op["scenario_hint"].replace("{theme}", theme)
    ed_hint = ed["summary_hint"].replace("{theme}", theme)

    return f"""
あなたは登録者30万人の「ゆっくり生き物劇場」YouTuberです。
生き物の一生を「物語」として描く5幕構成の動画で、
平均20万再生・視聴維持率55%超を叩き出すトッププレイヤーとして最高品質の構成を作ってください。

テーマ: 「{theme}」
目標尺: 15〜17分

ターゲット視聴者: 生き物に興味がある全年齢層（特に「知的好奇心が旺盛な大人」）

## 冒頭パターン: {op["name"]}
{op_hint}

## 結末パターン: {ed["name"]}
{ed_hint}

## 5幕構成（必ずこの構造で設計すること）

### 第1幕「出会い」(type: intro, 約2分)
- テーマの生き物との初遭遇
- 冒頭パターン「{op["name"]}」で展開する
- 霊夢の自己紹介→魔理沙の自己紹介→冒頭シナリオ→テーマ紹介→「ゆっくりしていってね」
- この生き物の「一言で言うとすごいところ」を予告して視聴者を引き込む

### 第2幕「誕生と試練」(type: chapter, 約4分)
- この生き物の誕生・幼少期を描く
- 生まれた瞬間から過酷な環境・天敵・低い生存率との戦い
- 「100匹生まれて大人になれるのは○匹」のような数字で衝撃を与える
- 霊夢が「かわいそう！」「がんばれ！」と感情移入する

### 第3幕「生存戦略」(type: chapter, 約4分)
- この生き物が持つ独自の進化・驚きの能力・生態
- 「こんなことができるのか！」と視聴者が驚く情報を集中投入
- 科学的な根拠・研究データを交えて解説
- 霊夢が「人間だったら○○みたいなものよね！」と人間に例える

### 第4幕「クライマックス」(type: chapter, 約4分)
- 最大の試練。天敵との直接対決、環境の激変、絶滅の危機
- **容赦なく厳しく描写する**（生存率1%、天敵に襲われる、極限環境）
- 人間との関わり（生息地破壊、保護活動、共存の課題）
- 視聴者が「どうなるの！？」とハラハラする展開

### 第5幕「生き様のまとめ」(type: summary, 約3分)
- 結末パターン「{ed["name"]}」で締める
- **必ずハッピーエンドにする**（生き延びる、保護される、希望がある）
- この生き物から学べること、人間の生活との接点
- 視聴者への問いかけ「みんなはこの生き物を見てどう感じた？コメントで教えてくれな」

## key_points の設計ルール
- 各セクションに4〜6個の具体的な情報を入れる
- **事実に基づく情報のみ**（嘘禁止。自信がない場合は「〜と報告されている」表現を使う）
- 数字を積極的に入れる（体長・体重・寿命・生存率・速度・繁殖数など）
- 「○○大学の研究で」「○○年の調査によると」など出典を可能な限り付ける
- 第4幕のkey_pointsは特に「視聴者の予想を裏切る展開」にすること

## ホワイトボード演出の設計
- chapterセクションのみにホワイトボードを設定（introとsummaryには不要）
- 各chapterに2〜4項目の短い要点（15文字以内）
- 例: 「生存率: 約0.1%」「天敵: ○○科の鳥類」「飛行速度: 時速○km」
- whiteboard_summaryは全体の要点を4〜6項目でまとめる

## 視聴者コメントを生む仕掛け
- 二項対立を1つ設ける（「この生き物は○○すべきか△△すべきか」、保護の是非など）
- 「みんなの身近にもいる生き物」との比較で共感を作る
- 「もしあなたがこの生き物だったら？」という問いかけ

以下の形式でJSONのみを出力してください。

{{
  "theme": "{theme}",
  "opening_pattern": "{opening_pattern}",
  "ending_pattern": "{ending_pattern}",
  "scenario": "冒頭シナリオ（冒頭パターン「{op["name"]}」に基づく1〜2文の場面設定）",
  "hook": "魔理沙の最初のセリフ（40〜60文字。テーマへの誘導）",
  "summary": "この動画で視聴者が得られること（80〜100字）",
  "sections": [
    {{
      "title": "セクションタイトル（視聴者が見たくなる名前）",
      "type": "intro | chapter | summary",
      "key_points": ["具体的な情報1（数字を含む）", "情報2", "情報3", "情報4"],
      "whiteboard": [
        {{"text": "要点テキスト（15文字以内）"}}
      ]
    }}
  ],
  "whiteboard_summary": ["全体要点1", "全体要点2", "全体要点3", "全体要点4"]
}}
"""


# ── 笑いの設計プロンプト ──────────────────────────────────

def build_comedy_design_prompt(theme: str, structure: dict) -> str:
    """テーマ・構成から「笑いのネタ」を事前に設計するプロンプト。
    台本生成の前に呼び出し、結果を build_script_prompt() に注入する。
    """
    scenario = structure.get("scenario", "")
    key_points_all = []
    for s in structure.get("sections", []):
        key_points_all.extend(s.get("key_points", [])[:3])
    key_points_text = "\n".join(f"  - {kp}" for kp in key_points_all[:12])

    return f"""あなたは「ゆっくり茶番劇」の放送作家です。
ゆっくり生き物劇場チャンネル（霊夢=感情担当、魔理沙=語り部）の動画で使う
「笑いのネタ」を事前に設計してください。

テーマ: {theme}
冒頭シナリオ: {scenario}
動画で扱う情報:
{key_points_text}

## キャラクター特性（笑いの設計に反映すること）
- 魔理沙 = 語り部。{theme}を正式名称で呼ぶ。生物学的に正確な情報を語る
- 霊夢 = 感情担当。{theme}にあだ名をつけたがる。感情移入が激しい

## 笑いの心理学（これに基づいて設計すること）
- 不一致理論: 霊夢の的外れなあだ名・勘違いでズレを作る
- 良性逸脱理論: 生き物の奇妙な生態を「人間で言うと」で笑いに変換
- 緊張解放理論: 厳しい生存の話のあとに、霊夢の脱力系リアクションで緩和
- 具体性の法則: 「すごい」は笑えない。「時速200kmで突っ込んでくる」は笑える

## 設計してほしい笑いのネタ（6種類）

### 1. あだ名暴走（3つ）
霊夢が{theme}につけるあだ名がどんどんエスカレートする。
魔理沙が「正式名称で呼べ！」とツッコむのが基本パターン。
- 1つ目: 見た目からの素朴なあだ名（「フサフサちゃん」「トゲトゲくん」等）
- 2つ目: 生態を知って更新されたあだ名（能力にちなむ）
- 3つ目: 完全に暴走した謎のあだ名（魔理沙が呆れる）

### 2. 人間で言うと（2つ）
生き物の生態を人間社会に例える笑い。
- 魔理沙が「わかりやすく言うとだな…」と人間に置き換えた爆笑級の例え話をする
- 霊夢が「それ○○じゃん！」と身近なものに結びつけてツッコむ
- スケールの極端な変換が笑いのカギ

### 3. 冒頭シナリオ用ボケ（1つ）
冒頭の霊夢のシナリオに仕込む具体的なボケ。
冒頭パターンに合わせた的外れな行動・発言。

### 4. Callback（伏線回収）設計（1つ）
序盤の何気ない発言を、終盤で回収して笑いに変えるネタ。
- 序盤のセリフ（何気ない一言）と、終盤の回収セリフをセットで設計

### 5. 天丼（繰り返し）ネタ（1つ）
霊夢が動画中に2〜3回繰り返す「同じ間違い」。
3回目で魔理沙が「お前まだそれ言ってるのかよ！」とキレるのがピーク。

### 6. 数字インパクトネタ（1つ）
テーマの生き物に関する「極端な数字」で視聴者を驚かせるネタ。
霊夢が「それ人間だったら○○ってこと！？」とオーバーリアクションする。

## 出力形式（JSONのみ・前置き不要）
{{
  "nickname_escalation": [
    {{"nickname": "あだ名", "reason": "なぜそう呼んだか", "marisa_tsukkomi": "魔理沙のツッコミ"}},
    {{"nickname": "...", "reason": "...", "marisa_tsukkomi": "..."}},
    {{"nickname": "...", "reason": "...", "marisa_tsukkomi": "..."}}
  ],
  "human_comparison": [
    {{"creature_fact": "生き物の事実", "human_analogy": "人間で言うと", "punchline": "オチ"}},
    {{"creature_fact": "...", "human_analogy": "...", "punchline": "..."}}
  ],
  "opening_boke": {{
    "reimu_action": "霊夢の具体的な行動",
    "comedy_structure": "勘違い or あだ名暴走 or 的外れリアクション",
    "punchline": "オチの方向性"
  }},
  "callback": {{
    "setup_line": "序盤の何気ないセリフ",
    "setup_context": "どの場面で使うか",
    "payoff_line": "終盤の回収セリフ",
    "payoff_context": "どの場面で回収するか"
  }},
  "tendon": {{
    "recurring_mistake": "霊夢が繰り返す間違い",
    "first_mention": "1回目（さらっと）",
    "second_mention": "2回目（魔理沙が呆れる）",
    "third_mention": "3回目（魔理沙がキレる）"
  }},
  "number_impact": {{
    "extreme_number": "極端な数字の事実",
    "human_scale": "人間に例えるとどうなるか",
    "reimu_overreaction": "霊夢のオーバーリアクション"
  }}
}}
"""


# ── 台本生成プロンプト ────────────────────────────────────

def build_script_prompt(theme: str, structure: dict,
                        comedy_design: dict | None = None) -> str:
    """構成から台本を生成するプロンプト。

    health の build_script_prompt と同じ出力JSON形式を使用する。
    """
    characters_desc = get_characters_description()

    sections_desc = ""
    for i, section in enumerate(structure.get("sections", []), 1):
        sections_desc += f"\n【{section['title']}】（タイプ: {section.get('type', 'chapter')}）\n"
        for point in section.get("key_points", []):
            sections_desc += f"  - {point}\n"

    hook = structure.get("hook", "")
    scenario = structure.get("scenario", "")
    opening_pattern = structure.get("opening_pattern", "A")
    ending_pattern = structure.get("ending_pattern", "1")

    op = OPENING_PATTERNS.get(opening_pattern, OPENING_PATTERNS["A"])
    ed = ENDING_PATTERNS.get(ending_pattern, ENDING_PATTERNS["1"])

    scenario_section = f"""
## 冒頭シナリオ設定（{op["name"]}パターン）
{scenario}
""" if scenario else ""

    # 笑いの事前設計結果を注入
    comedy_section = ""
    if comedy_design:
        import json as _json
        comedy_section = "\n## 笑いの事前設計（放送作家が設計済み。必ず台本に組み込むこと）\n"
        comedy_section += "以下は別の放送作家が事前に設計した笑いのネタです。台本の本編に分散配置してください。\n"
        comedy_section += "**冒頭（intro）には詰め込まないこと。** 冒頭はボケ→ツッコミの1往復だけ。\n\n"

        nicknames = comedy_design.get("nickname_escalation", [])
        if nicknames:
            comedy_section += "### あだ名暴走（霊夢のあだ名が3段階でエスカレート）\n"
            for i, n in enumerate(nicknames, 1):
                comedy_section += f"  {i}. あだ名: {n.get('nickname', '')}\n"
                comedy_section += f"     理由: {n.get('reason', '')}\n"
                comedy_section += f"     魔理沙: {n.get('marisa_tsukkomi', '')}\n"

        comparisons = comedy_design.get("human_comparison", [])
        if comparisons:
            comedy_section += "\n### 人間で言うと（解説中に組み込め）\n"
            for i, c in enumerate(comparisons, 1):
                comedy_section += f"  {i}. 事実: {c.get('creature_fact', '')}\n"
                comedy_section += f"     人間だと: {c.get('human_analogy', '')}\n"
                comedy_section += f"     オチ: {c.get('punchline', '')}\n"

        opening = comedy_design.get("opening_boke")
        if opening:
            comedy_section += f"\n### 冒頭シナリオ用ボケ\n"
            comedy_section += f"  霊夢の行動: {opening.get('reimu_action', '')}\n"
            comedy_section += f"  構造: {opening.get('comedy_structure', '')}\n"
            comedy_section += f"  オチの方向: {opening.get('punchline', '')}\n"

        callback = comedy_design.get("callback")
        if callback:
            comedy_section += f"\n### Callback（伏線回収）\n"
            comedy_section += f"  序盤: {callback.get('setup_line', '')}（{callback.get('setup_context', '')}）\n"
            comedy_section += f"  終盤: {callback.get('payoff_line', '')}（{callback.get('payoff_context', '')}）\n"

        tendon = comedy_design.get("tendon")
        if tendon:
            comedy_section += f"\n### 天丼（繰り返しギャグ）\n"
