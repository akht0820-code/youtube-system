# ── パターンを事前コンパイル（起動時1回だけ） ──────────────────
# キーを長い順にソートして最長マッチを保証する
_sorted_keys = sorted(STATIC_DICT.keys(), key=len, reverse=True)
_STATIC_PATTERN = re.compile("|".join(re.escape(k) for k in _sorted_keys))


# ── Step1: 静的辞書適用 ─────────────────────────────────────────

def apply_dict(text: str) -> str:
    """テキストに静的発音辞書を適用して補正済みテキストを返す。
    漢字→かな変換は tts_aquestalk.py の fugashi で行うため、ここでは
    英字略語・単位記号・数値表現など fugashi が誤読しやすい表記のみ扱う。
    """
    return _STATIC_PATTERN.sub(lambda m: STATIC_DICT[m.group(0)], text)


def apply_dict_to_script(script: dict) -> tuple[dict, int]:
    """
    台本全体に静的発音辞書を適用する。
    各行に synthesis_text フィールドを追加し、元の text は変更しない。
    STATIC_DICT 適用後、数字+助数詞を日本語読みに正規化する。

    Returns:
        (補正済み台本, 置換した行数)
    """
    # 数字正規化関数を遅延インポート（tts_aquestalk.py と同じロジックを共有）
    try:
        from tts_aquestalk import normalize_numbers as _norm_nums
    except ImportError:
        _norm_nums = None

    script = copy.deepcopy(script)
    corrected_lines = 0

    for section in script.get("sections", []):
        for line in section.get("lines", []):
            original = line.get("text", "")
            # 数字正規化を先に実行（"2.5倍"等をひらがな化してから辞書を適用）
            # ※ STATIC_DICTに"5倍→ごばい"等があり、先に辞書を適用すると
            #   "2.5倍"→"2.ごばい"と部分マッチしてしまうため
            corrected = original
            if _norm_nums:
                corrected = _norm_nums(corrected)
            corrected = apply_dict(corrected)
            line["synthesis_text"] = corrected
            if corrected != original:
                corrected_lines += 1

    return script, corrected_lines


# ── Step2: AI発音チェック ───────────────────────────────────────

# 「難しい可能性がある」テキストを抽出する正規表現
# - 英大文字が2字以上続く（略語: EPA, LDL ...）
# - 英字＋数字＋単位（3mg, 10% ...）
# - 記号が含まれる
_HARD_TOKEN_RE = re.compile(
    r"""
    [A-Z]{2,}           # 英大文字2字以上（略語）
    | \d+\s*[a-zA-Zμ%℃°×÷±≥≤]+  # 数字+単位
    | [A-Za-z]{3,}      # 3文字以上の英字
    | [μ%℃°×÷±≥≤→⇒]   # 特殊記号
    """,
    re.VERBOSE,
)


def _extract_hard_tokens(script: dict) -> list[str]:
    """台本から「VOICEVOXが読み間違えそうな」トークンを一意に抽出する"""
    found = set()
    for section in script.get("sections", []):
        for line in section.get("lines", []):
            text = line.get("synthesis_text") or line.get("text", "")
            for m in _HARD_TOKEN_RE.finditer(text):
                token = m.group(0).strip()
                if token and token not in STATIC_DICT:
                    found.add(token)
    return sorted(found)


def ai_check_script(script: dict, llm, model: str) -> tuple[dict, int]:
    """
    AIで台本全体の読み方をチェックし、静的辞書でカバーできていない
    読み間違い候補を補正する。

    Args:
        script: apply_dict_to_script() 適用済みの台本
        llm:    LLMクライアント（GeminiLLMClient等）
        model:  使用するモデル名（model_config.SIMPLE 推奨）

    Returns:
        (補正済み台本, AIが補正した行数)
    """
    from script_repair import extract_json_safe

    hard_tokens = _extract_hard_tokens(script)
    if not hard_tokens:
        print("  AI発音チェック: 対象トークンなし → スキップ")
        return script, 0

    print(f"  AI発音チェック: {len(hard_tokens)} トークンをチェック中...")

    token_list = "\n".join(f"- {t}" for t in hard_tokens)
    prompt = f"""あなたはVOICEVOX（日本語テキスト読み上げエンジン）の発音チェッカーです。

以下の単語・表記リストの中で、VOICEVOXが正しく読めない可能性があるものを特定し、
正しい読み方（ひらがなまたはカタカナ）を教えてください。

## チェック対象リスト
{token_list}

## VOICEVOXが間違えやすいパターン
- 英字略語（VOICEVOXはアルファベットを英語読みすることがある）
- 数字＋単位の組み合わせ（「3mg」→「さんみりぐらむ」と読む等）
- 医療・栄養素の専門外来語（カタカナの読み崩れ）

## 出力ルール
- 正しく読めるものは含めない
- 補正不要なら空配列 [] を返す
- JSONの配列形式のみで出力（前置き・説明不要）

## 出力形式
[
  {{"surface": "元の表記（完全一致）", "reading": "読み方（ひらがな or カタカナ）"}},
  ...
]
"""
    try:
        raw = llm.generate(prompt, model)
        corrections = extract_json_safe(raw)

        if not isinstance(corrections, list) or not corrections:
            print("  AI発音チェック: 補正候補なし")
            return script, 0

        # 動的辞書を構築
        dynamic_dict: dict[str, str] = {}
        for c in corrections:
            if isinstance(c, dict) and c.get("surface") and c.get("reading"):
                dynamic_dict[c["surface"]] = c["reading"]

        if not dynamic_dict:
            return script, 0

        print(f"  AI発音チェック: {len(dynamic_dict)} 件の補正候補を取得")
        for surface, reading in dynamic_dict.items():
            print(f"    「{surface}」→「{reading}」")

        # 動的辞書を台本に適用
        d_keys = sorted(dynamic_dict.keys(), key=len, reverse=True)
        d_pattern = re.compile("|".join(re.escape(k) for k in d_keys))

        count = 0
        for section in script.get("sections", []):
            for line in section.get("lines", []):
                original = line.get("synthesis_text") or line.get("text", "")
                corrected = d_pattern.sub(
                    lambda m: dynamic_dict[m.group(0)], original
                )
                if corrected != original:
                    line["synthesis_text"] = corrected
                    count += 1

        return script, count

    except Exception as e:
        print(f"  [!] AI発音チェック失敗: {e} -> スキップして続行")
        return script, 0


